import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 393, height: 852 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
async function open(name) {
  await page.goto(`http://127.0.0.1:5173/#/pages/${name}/${name}`)
  await page.waitForSelector('.original-h1', { timeout: 30000 })
}
async function click(text) {
  const button = page.locator('uni-button').filter({ has: page.getByText(text, { exact: true }) }).filter({ visible: true })
  if (await button.count()) await button.first().click()
  else await page.getByText(text, { exact: true }).filter({ visible: true }).first().click()
}
